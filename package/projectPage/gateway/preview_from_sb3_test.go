package gateway

import (
	"archive/zip"
	"bytes"
	"testing"
)

func TestPreviewFromSb3Archive_stagePNG(t *testing.T) {
	png := []byte{
		0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
		0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
		0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00,
		0x0a, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
		0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49,
		0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
	}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	pj, err := zw.Create("project.json")
	if err != nil {
		t.Fatal(err)
	}
	_, _ = pj.Write([]byte(`{"targets":[{"isStage":true,"currentCostume":0,"costumes":[{"md5ext":"a.png","dataFormat":"png"}]}]}`))
	img, err := zw.Create("a.png")
	if err != nil {
		t.Fatal(err)
	}
	_, _ = img.Write(png)
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	data, mime, ok := previewFromSb3Archive(buf.Bytes())
	if !ok {
		t.Fatal("expected preview")
	}
	if mime != "image/png" {
		t.Fatalf("mime=%s", mime)
	}
	if !bytes.Equal(data, png) {
		t.Fatal("png mismatch")
	}
}
